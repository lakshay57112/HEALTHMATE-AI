"""Step 10 — save patient-verified information and update connected modules.

Only reached after the patient reviewed (and possibly edited) the extraction and pressed Confirm.
Input is re-validated with the same Pydantic schemas; schedules are generated by deterministic rules.
"""
from __future__ import annotations

from datetime import date, datetime, timedelta, timezone

from fastapi import HTTPException
from pydantic import ValidationError
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import (
    Appointment,
    HealthMeasurement,
    MedicalDocument,
    MedicalReport,
    PatientProfile,
    Prescription,
    PrescriptionMedicine,
    ReportParameter,
    User,
)
from app.services import rag, reports, scheduling, timeutil
from app.services.extraction.schemas import SCHEMAS
from app.services.medical_knowledge import canonicalize
from app.services.notify import create_notification

PILL_COLORS = ["#4D8B73", "#E9AA53", "#6C8EBF", "#D96C6C", "#9B7BB8", "#5BA4A4", "#C9895B"]


def _d(iso: str | None) -> date | None:
    try:
        return date.fromisoformat(iso) if iso else None
    except ValueError:
        return None


def commit_document(db: Session, user: User, doc: MedicalDocument, payload: dict) -> dict:
    doc_type = payload.get("type") or doc.detected_type
    if doc_type not in SCHEMAS and doc_type != "other":
        raise HTTPException(422, "Unknown document type")
    options = payload.get("options") or {}
    result: dict = {"type": doc_type, "created": {}}
    profile = db.scalar(select(PatientProfile).where(PatientProfile.user_id == user.id))
    injection = "possible_injection" in (doc.flags or [])

    if doc_type == "other":
        doc.document_date = _d(payload.get("data", {}).get("document_date"))
    else:
        try:
            data = SCHEMAS[doc_type].model_validate(payload.get("data") or {})
        except ValidationError as err:
            raise HTTPException(422, {"message": "Some fields are invalid", "errors": err.errors()[:10]}) from err

    if doc_type == "lab_report":
        if not data.tests:
            raise HTTPException(422, "Add at least one test result before confirming")
        rpt = MedicalReport(user_id=user.id, document_id=doc.id, title=data.title or "Lab report", report_date=_d(data.report_date), lab_name=data.lab_name)
        db.add(rpt)
        for i, t in enumerate(data.tests):
            val = reports.to_float(t.value_text)
            lo, hi = t.ref_low, t.ref_high
            if (lo is None and hi is None) and t.ref_text:
                from app.services.extraction.rules import parse_range

                lo, hi = parse_range(t.ref_text)
            rpt.parameters.append(ReportParameter(user_id=user.id, position=i, test_group=t.test_group, name=t.name, canonical_name=canonicalize(t.name),
                                                  value=val, value_text=t.value_text, unit=t.unit, ref_low=lo, ref_high=hi, ref_text=t.ref_text,
                                                  status=reports.compute_status(val, lo, hi), report_date=rpt.report_date))
        db.flush()
        rpt.summary = reports.build_summary(rpt)
        doc.document_date = rpt.report_date
        # Connected module: fasting glucose from a lab report becomes a (report-sourced) measurement.
        for p in rpt.parameters:
            if p.canonical_name == "fasting_glucose" and p.value is not None:
                when = datetime.combine(rpt.report_date or date.today(), datetime.min.time(), tzinfo=timezone.utc) + timedelta(hours=3)
                db.add(HealthMeasurement(user_id=user.id, kind="glucose", value=p.value, unit=p.unit or "mg/dL", context="fasting",
                                         measured_at=when, source="report", note=f"From {rpt.title}"))
        rag.index_chunks(db, user.id, document_id=doc.id, source_type="report", label=f"{rpt.title} ({rpt.report_date or 'undated'})",
                         texts=reports.fact_lines(rpt), verified=True)
        result["created"] = {"report_id": rpt.id, "parameters": len(rpt.parameters),
                             "abnormal": sum(1 for p in rpt.parameters if p.status in ("high", "low"))}
        title, body = "Report saved", f"{rpt.title}: {result['created']['abnormal']} result(s) outside range. Tap to see a simple explanation."

    elif doc_type == "prescription":
        selected = payload.get("data", {}).get("medicines", [])
        rx = Prescription(user_id=user.id, document_id=doc.id, doctor_name=data.doctor_name, clinic=data.clinic, prescribed_date=_d(data.prescribed_date),
                          notes=data.notes, status="verified", verified_at=timeutil.now_utc())
        db.add(rx)
        db.flush()
        existing_count = db.query(PrescriptionMedicine).filter(PrescriptionMedicine.user_id == user.id).count()
        replaced = 0
        if options.get("replace_duplicates"):
            keys = {(m.generic_name or m.name).lower().split("+")[0].strip() for i, m in enumerate(data.medicines)
                    if not (i < len(selected) and selected[i].get("include") is False)}
            for old in db.scalars(select(PrescriptionMedicine).where(PrescriptionMedicine.user_id == user.id, PrescriptionMedicine.is_active.is_(True))).all():
                if (old.generic_name or old.name).lower().split("+")[0].strip() in keys:
                    old.is_active = False
                    scheduling.regenerate_schedules(db, old)
                    replaced += 1
        created = []
        for i, m in enumerate(data.medicines):
            raw = selected[i] if i < len(selected) else {}
            if raw.get("include") is False:
                continue
            fp = scheduling.parse_frequency(m.frequency)
            slots = [s for s in (raw.get("slots") or fp.slots) if s in scheduling.SLOTS]
            if not slots and not fp.as_needed:
                raise HTTPException(422, f"Please choose when to take {m.name} (morning/afternoon/evening/night), or untick it.")
            start = _d(raw.get("start_date")) or rx.prescribed_date or timeutil.local_today(profile.timezone if profile else None)
            end = start + timedelta(days=m.duration_days - 1) if m.duration_days else None
            med = PrescriptionMedicine(user_id=user.id, prescription_id=rx.id, name=m.name, brand_name=m.brand_name, generic_name=m.generic_name, form=m.form,
                                       strength=m.strength, dosage=m.dosage, frequency=m.frequency, slots=slots, meal_relation=m.meal_relation,
                                       duration_days=m.duration_days, start_date=start, end_date=end, instructions=m.instructions, source="prescription",
                                       verified=True, as_needed=fp.as_needed, stock_count=raw.get("stock_count"),
                                       color=PILL_COLORS[(existing_count + len(created)) % len(PILL_COLORS)])
            db.add(med)
            db.flush()
            scheduling.regenerate_schedules(db, med)
            created.append(med)
        appt_id = None
        if data.follow_up_date and options.get("create_follow_up"):
            appt = Appointment(user_id=user.id, doctor_name=data.doctor_name or "Doctor", clinic=data.clinic, source="document", document_id=doc.id,
                               prescription_id=rx.id, scheduled_at=timeutil.local_dt(_d(data.follow_up_date), options.get("follow_up_time", "10:00"), profile.timezone if profile else None),
                               notes="Follow-up from prescription")
            db.add(appt)
            db.flush()
            appt_id = appt.id
        facts = [f"Verified prescription from {data.doctor_name or 'doctor'} ({data.clinic or ''}) dated {data.prescribed_date or 'unknown'}."]
        facts += [f"{m.name} {m.strength or ''} — {m.dosage or ''} {m.frequency or ''}, {m.meal_relation.replace('_', ' ')}, slots: {', '.join(m.slots) or 'as needed'}, "
                  f"from {m.start_date} to {m.end_date or 'ongoing'}." for m in created]
        if data.notes:
            facts.append(f"Doctor notes: {data.notes}")
        rag.index_chunks(db, user.id, document_id=doc.id, source_type="prescription", label=f"Prescription {data.prescribed_date or ''}".strip(),
                         texts=["\n".join(facts)], verified=True)
        result["created"] = {"prescription_id": rx.id, "medicines": len(created), "appointment_id": appt_id, "replaced": replaced}
        title, body = "Prescription verified", f"{len(created)} medicine(s) added to your schedule."

    elif doc_type in ("diet_advice", "consultation_note"):
        instr = data.instructions if doc_type == "diet_advice" else data.diet_instructions
        restr = data.restrictions
        if profile:
            entries = list(profile.doctor_diet_instructions or [])
            src_date = (data.advice_date if doc_type == "diet_advice" else data.visit_date) or date.today().isoformat()
            for line in instr:
                entries.append({"text": line, "doctor": data.doctor_name, "date": src_date, "document_id": doc.id})
            for tag in restr:
                entries.append({"tag": tag, "doctor": data.doctor_name, "date": src_date, "document_id": doc.id})
            profile.doctor_diet_instructions = entries
        appt_id = None
        if doc_type == "consultation_note":
            visit = _d(data.visit_date)
            appt = Appointment(user_id=user.id, doctor_name=data.doctor_name or "Doctor", specialization=data.specialization, clinic=data.clinic,
                               scheduled_at=timeutil.local_dt(visit or date.today(), "10:00", profile.timezone if profile else None), status="completed",
                               consultation_summary="\n".join(filter(None, [data.summary] + data.advice)), document_id=doc.id, source="document")
            db.add(appt)
            if data.follow_up_date and options.get("create_follow_up"):
                db.add(Appointment(user_id=user.id, doctor_name=data.doctor_name or "Doctor", specialization=data.specialization, clinic=data.clinic,
                                   scheduled_at=timeutil.local_dt(_d(data.follow_up_date), options.get("follow_up_time", "10:00"), profile.timezone if profile else None),
                                   source="document", document_id=doc.id, notes="Follow-up visit"))
            db.flush()
            appt_id = appt.id
        facts = [f"Doctor's {'diet advice' if doc_type == 'diet_advice' else 'consultation note'} from {data.doctor_name or 'doctor'}:"] + [f"- {x}" for x in instr]
        if doc_type == "consultation_note" and data.summary:
            facts.append(f"Summary: {data.summary}")
            facts += [f"- {x}" for x in data.advice if x not in instr]
        rag.index_chunks(db, user.id, document_id=doc.id, source_type="diet" if doc_type == "diet_advice" else "consultation",
                         label="Doctor's diet advice" if doc_type == "diet_advice" else "Consultation note", texts=["\n".join(facts)], verified=True)
        from app.services.nutrition import generate_plan

        generate_plan(db, user)
        result["created"] = {"instructions": len(instr), "restrictions": restr, "appointment_id": appt_id}
        title, body = "Doctor's advice saved", "Your meal plan has been updated to follow your doctor's instructions."

    elif doc_type == "appointment":
        if not data.date:
            raise HTTPException(422, "Please enter the appointment date")
        appt = Appointment(user_id=user.id, doctor_name=data.doctor_name or "Doctor", specialization=data.specialization, clinic=data.clinic, address=data.address,
                           phone=data.phone, scheduled_at=timeutil.local_dt(_d(data.date), data.time or "10:00", profile.timezone if profile else None),
                           notes=data.notes, document_id=doc.id, source="document")
        db.add(appt)
        db.flush()
        rag.index_chunks(db, user.id, document_id=doc.id, source_type="appointment", label="Appointment",
                         texts=[f"Appointment with {appt.doctor_name} ({data.specialization or ''}) at {data.clinic or ''} on {data.date} {data.time or ''}."], verified=True)
        result["created"] = {"appointment_id": appt.id}
        title, body = "Appointment added", f"{appt.doctor_name} on {data.date}."
    else:
        title, body = "Document saved", "Stored in your health history."

    if doc.ocr_text:
        rag.index_document_text(db, user.id, doc.id, doc.filename, doc.ocr_text, injection)
    if doc_type != "other":
        stored = dict(doc.extraction or {})
        stored["verified_data"] = payload.get("data")
        doc.extraction = stored
    doc.status = "verified"
    doc.verified_at = timeutil.now_utc()
    if doc_type != "other":
        doc.detected_type = doc_type
    create_notification(db, user.id, "document", title, body, data={"document_id": doc.id, "url": f"/app/documents/{doc.id}"}, push=False)
    return result
